// Copies the parity fixture (docs/fixtures/muttertag.billet.json, the live Mother's Day card as a
// billet document) into the dev billet preview, which cannot import a file outside src/. The
// Playwright parity test reads the JSON itself. Runs in prestart; `npm run parity:gen` by hand.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const SOURCE = new URL('../../../docs/fixtures/muttertag.billet.json', import.meta.url);
const TARGET = fileURLToPath(
  new URL(
    '../../src/app/features/dev/billet-preview/parity-document.generated.ts',
    import.meta.url,
  ),
);

const fixture = JSON.parse(await readFile(SOURCE, 'utf8'));
const source = `// Generated by e2e/support/generate-parity-document.mjs from docs/fixtures/muttertag.billet.json - do not edit

/** The live Mother's Day card as a billet document; it enters the app through migrateDocument(). */
export const PARITY_DOCUMENT: unknown = ${JSON.stringify(fixture, null, 2)};
`;
const options = (await prettier.resolveConfig(TARGET)) ?? {};
const formatted = await prettier.format(source, { ...options, filepath: TARGET });
const current = await readFile(TARGET, 'utf8').catch(() => '');
if (current !== formatted) {
  await writeFile(TARGET, formatted);
  console.log('Wrote', TARGET);
}
