// Builds the Bootstrap Icons subset the app uses and writes src/styles/_icons.generated.scss (never
// edit it by hand): the @font-face, the base .bi rule and one ::before rule per icon.
// Icons in the subset: every `bi-<name>` in src/**/*.{html,ts} (specs excluded), plus
// src/styles/icons/dynamic-icons.json for names that are assembled at runtime and so never appear
// literally. Codepoints come from node_modules/bootstrap-icons/font/bootstrap-icons.json; a name that
// does not exist there fails the script (exit 1, nothing written).
// The font is referenced by url() from node_modules, so the Angular build bundles it (hashed file
// name, fails the build if it is missing) and no copy of it lives in the repo.
// Runs via the prestart/prebuild/pretest npm hooks.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'src');
const ALLOW_LIST = join(SRC, 'styles', 'icons', 'dynamic-icons.json');
const PACKAGE = join(root, 'node_modules', 'bootstrap-icons');
const CODEPOINTS = join(PACKAGE, 'font', 'bootstrap-icons.json');
const FONT = join(PACKAGE, 'font', 'fonts', 'bootstrap-icons.woff2');
const OUT = join(SRC, 'styles', '_icons.generated.scss');

// A class token: not preceded by a word character or hyphen, so "combi-x" or "ui-bi-x" never count.
const USAGE = /(?<![\w-])bi-([a-z0-9]+(?:-[a-z0-9]+)*)/g;
const CLASS_NAME = /^bi-[a-z0-9]+(?:-[a-z0-9]+)*$/;

function fail(title, lines) {
  console.error(`${title}:\n  ${lines.join('\n  ')}`);
  process.exit(1);
}

function sourceFiles(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) sourceFiles(path, out);
    else if (/\.(html|ts)$/.test(entry.name) && !entry.name.endsWith('.spec.ts')) out.push(path);
  }
  return out;
}

/** icon name -> the files that use it (for the error message). */
function collectUsages() {
  const usages = new Map();
  const note = (name, where) => usages.set(name, [...(usages.get(name) ?? []), where]);
  for (const file of sourceFiles(SRC)) {
    const where = relative(root, file).replaceAll('\\', '/');
    for (const m of readFileSync(file, 'utf8').matchAll(USAGE)) note(m[1], where);
  }
  const allowList = JSON.parse(readFileSync(ALLOW_LIST, 'utf8')).icons ?? [];
  const where = relative(root, ALLOW_LIST).replaceAll('\\', '/');
  const malformed = allowList.filter((c) => typeof c !== 'string' || !CLASS_NAME.test(c));
  if (malformed.length) fail(`${where}: entries must be bi-<name> class names`, malformed);
  for (const className of allowList) note(className.slice(3), where);
  return usages;
}

const hex = (codepoint) => codepoint.toString(16);

function render(names, codepoints, version) {
  const fontUrl = relative(dirname(OUT), FONT).replaceAll('\\', '/');
  const total = Object.keys(codepoints).length;
  return [
    '// AUTO-GENERATED by scripts/generate-icons.mjs. Do not edit.',
    `// ${names.length} of ${total} Bootstrap Icons ${version}: every bi-<name> in src/**/*.{html,ts}`,
    '// plus src/styles/icons/dynamic-icons.json. Rules as in bootstrap-icons/font/bootstrap-icons.css.',
    '',
    '@font-face {',
    '    font-display: block;',
    "    font-family: 'bootstrap-icons';",
    `    src: url('${fontUrl}') format('woff2');`,
    '}',
    '',
    '.bi::before,',
    "[class^='bi-']::before,",
    "[class*=' bi-']::before {",
    '    display: inline-block;',
    "    font-family: 'bootstrap-icons' !important;",
    '    font-style: normal;',
    '    font-weight: normal !important;',
    '    font-variant: normal;',
    '    text-transform: none;',
    '    line-height: 1;',
    '    vertical-align: -0.125em;',
    '    -webkit-font-smoothing: antialiased;',
    '    -moz-osx-font-smoothing: grayscale;',
    '}',
    '',
    // The host <i> is italic by default. It renders no text, but its line box still loads the
    // surrounding font in italic (Inter 800 italic next to every icon in a 600-weight label).
    '.bi {',
    '    font-style: normal;',
    '}',
    ...names.flatMap((name) => [
      '',
      `.bi-${name}::before {`,
      `    content: '\\${hex(codepoints[name])}';`,
      '}',
    ]),
    '',
  ].join('\n');
}

function main() {
  if (!existsSync(CODEPOINTS) || !existsSync(FONT)) {
    fail('bootstrap-icons is not installed', ['run npm install']);
  }
  const codepoints = JSON.parse(readFileSync(CODEPOINTS, 'utf8'));
  const { version } = JSON.parse(readFileSync(join(PACKAGE, 'package.json'), 'utf8'));
  const usages = collectUsages();

  const unknown = [...usages].filter(([name]) => !Object.hasOwn(codepoints, name));
  if (unknown.length) {
    fail(
      `Unknown Bootstrap Icons ${version} name(s)`,
      unknown.map(([name, files]) => `bi-${name} (${[...new Set(files)].join(', ')})`),
    );
  }

  const names = [...usages.keys()].sort();
  const content = render(names, codepoints, version);
  const changed = !existsSync(OUT) || readFileSync(OUT, 'utf8') !== content;
  if (changed) writeFileSync(OUT, content);
  const summary = changed ? 'wrote _icons.generated.scss' : 'output unchanged';
  console.log(`icons -> ${names.length} of ${Object.keys(codepoints).length} icons; ${summary}`);
}

main();
