import { weightLabel } from './css.mjs';

export const GENERATED_BY = 'Generated by tools/asset-pipeline/fonts/merge-fonts.mjs - do not edit';
export const CATEGORY_ORDER = ['serif', 'sans', 'display', 'script', 'handwriting'];

const SUBSET_ORDER = ['latin-ext', 'all', 'latin'];

export function sortFamilies(families) {
  return [...families].sort(
    (a, b) =>
      CATEGORY_ORDER.indexOf(a.category) - CATEGORY_ORDER.indexOf(b.category) ||
      a.family.localeCompare(b.family, 'en'),
  );
}

export function sortFaces(faces) {
  return [...faces].sort(
    (a, b) =>
      (a.style === 'italic') - (b.style === 'italic') ||
      a.weight.min - b.weight.min ||
      a.weight.max - b.weight.max ||
      SUBSET_ORDER.indexOf(a.subset) - SUBSET_ORDER.indexOf(b.subset),
  );
}

export function renderFontsCss(families) {
  const out = [`/* ${GENERATED_BY} */`, ''];
  for (const fam of [...families].sort((a, b) => a.id.localeCompare(b.id, 'en'))) {
    out.push(`/* ${fam.family} */`);
    for (const face of sortFaces(fam.faces)) {
      out.push(
        '@font-face {',
        `  font-family: '${fam.family}';`,
        `  font-style: ${face.style};`,
        `  font-weight: ${weightLabel(face.weight)};`,
        '  font-display: swap;',
        `  src: url('${face.dest}') format('woff2');`,
      );
      if (face.unicodeRange) out.push(`  unicode-range: ${face.unicodeRange};`);
      out.push('}');
    }
    out.push('');
  }
  return out.join('\n');
}

export function renderCatalog(families) {
  const entries = sortFamilies(families).map((fam) =>
    [
      '  {',
      `    id: '${fam.id}',`,
      `    family: '${fam.family}',`,
      `    category: '${fam.category}',`,
      `    weights: [${fam.weights.join(', ')}],`,
      `    italicWeights: [${fam.italicWeights.join(', ')}],`,
      `    variable: ${fam.variable},`,
      `    fallback: "${fam.fallback}",`,
      '  },',
    ].join('\n'),
  );
  return `// ${GENERATED_BY}

export type FontCategory = ${CATEGORY_ORDER.map((c) => `'${c}'`).join(' | ')};

export interface FontCatalogEntry {
  readonly id: string;
  readonly family: string;
  readonly category: FontCategory;
  readonly weights: readonly number[];
  readonly italicWeights: readonly number[];
  readonly variable: boolean;
  readonly fallback: string;
}

export const FONT_CATALOG = [
${entries.join('\n')}
] as const satisfies readonly FontCatalogEntry[];

export type FontId = (typeof FONT_CATALOG)[number]['id'];

export const FONT_BY_ID: ReadonlyMap<FontId, FontCatalogEntry> = new Map(
  FONT_CATALOG.map((entry): [FontId, FontCatalogEntry] => [entry.id, entry]),
);
`;
}

function licenseLink(fam) {
  const dir = fam.family.toLowerCase().replace(/[^a-z0-9]/g, '');
  const [folder, file] =
    fam.license === 'Apache-2.0' ? ['apache', 'LICENSE.txt'] : ['ofl', 'OFL.txt'];
  return `https://github.com/google/fonts/blob/main/${folder}/${dir}/${file}`;
}

export function renderLicenses(families) {
  const rows = sortFamilies(families).map(
    (fam) =>
      `| ${fam.family} | ${fam.sources.join(', ')} | ${fam.license} | [text](${licenseLink(fam)}) |`,
  );
  return `# Font licenses

${GENERATED_BY}.

Every family here is a Google Fonts family, served as self-hosted woff2 subsets (latin and
latin-ext). "Source" is where the pipeline took the files from; the local sources are earlier
projects that self-hosted the same Google Fonts files. OFL-1.1 and Apache-2.0 both allow bundling
and serving the fonts with the app; the linked license text is the upstream copy in the
google/fonts repository.

| Family | Source | License | License text |
| --- | --- | --- | --- |
${rows.join('\n')}
`;
}

const escapeHtml = (s) =>
  String(s).replace(
    /[&<>"']/g,
    (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c],
  );

export function renderPreview(families, manifest, issues) {
  const sections = CATEGORY_ORDER.map((category) => {
    const members = sortFamilies(families).filter((f) => f.category === category);
    if (members.length === 0) return '';
    const cards = members.map((fam) => {
      const stack = escapeHtml(fam.fallback);
      const rows = [
        ...fam.weights.map((w) => ({ w, style: 'normal' })),
        ...fam.italicWeights.map((w) => ({ w, style: 'italic' })),
      ].map(
        ({ w, style }) =>
          `        <div class="row"><span class="label">${w}${style === 'italic' ? ' italic' : ''}</span><p class="sample" style="font-family: ${stack}; font-weight: ${w}; font-style: ${style}">${escapeHtml(manifest.sampleText)}</p></div>`,
      );
      const baseWeight = fam.weights.includes(400) ? 400 : fam.weights[0];
      const note = issues.get(fam.id);
      return `      <article class="family" data-name="${escapeHtml(`${fam.family} ${fam.id}`.toLowerCase())}">
        <header>
          <h3>${escapeHtml(fam.family)}</h3>
          <p class="meta">${escapeHtml(fam.id)} · ${fam.variable ? 'variable' : 'static'} · ${escapeHtml(fam.sources.join(', '))} · ${escapeHtml(fam.license)}</p>
          ${note ? `<p class="warn">${escapeHtml(note)}</p>` : ''}
        </header>
${rows.join('\n')}
        <div class="row ext"><span class="label">latin-ext</span><p class="sample-ext" style="font-family: ${stack}; font-weight: ${baseWeight}">${escapeHtml(manifest.latinExtSample)}</p></div>
      </article>`;
    });
    return `    <section>
      <h2>${category} <span class="count">${members.length}</span></h2>
${cards.join('\n')}
    </section>`;
  }).filter(Boolean);

  return `<!doctype html>
<!-- ${GENERATED_BY} -->
<html lang="de">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Font Library Preview</title>
    <link rel="stylesheet" href="../../../billet-studio-frontend/public/fonts/fonts.css" />
    <style>
      :root {
        --bg: #faf8f5;
        --surface: #ffffff;
        --text: #1d1b19;
        --muted: #6b645c;
        --line: #e6e1da;
        --warn: #9a3412;
        color-scheme: light dark;
      }
      @media (prefers-color-scheme: dark) {
        :root {
          --bg: #171513;
          --surface: #211f1c;
          --text: #f2eee9;
          --muted: #a8a097;
          --line: #35312c;
          --warn: #fdba74;
        }
      }
      * { box-sizing: border-box; }
      body { margin: 0; background: var(--bg); color: var(--text); font: 1rem/1.5 system-ui, sans-serif; }
      .bar { display: flex; flex-wrap: wrap; gap: 0.75rem 1.25rem; align-items: center; padding: 0.75rem 1rem; background: var(--surface); border-bottom: 1px solid var(--line); }
      @media (min-width: 48rem) and (min-height: 36rem) {
        .bar { position: sticky; top: 0; z-index: 1; }
      }
      .bar h1 { margin: 0; font-size: 1rem; }
      .bar label { display: flex; gap: 0.5rem; align-items: center; font-size: 0.875rem; color: var(--muted); }
      .bar input[type='text'], .bar input[type='search'] { font: inherit; padding: 0.25rem 0.5rem; border: 1px solid var(--line); border-radius: 0.375rem; background: var(--bg); color: var(--text); min-width: 0; }
      .bar input[type='text'] { width: min(28rem, 100%); }
      main { max-width: 72rem; margin: 0 auto; padding: 1rem; }
      h2 { margin: 2rem 0 0.75rem; font-size: 0.875rem; letter-spacing: 0.08em; text-transform: uppercase; color: var(--muted); }
      .count { font-weight: 400; }
      .family { background: var(--surface); border: 1px solid var(--line); border-radius: 0.5rem; padding: 1rem; margin-bottom: 1rem; }
      .family header { margin-bottom: 0.5rem; }
      .family h3 { margin: 0; font-size: 1.125rem; }
      .meta { margin: 0; font-size: 0.8125rem; color: var(--muted); }
      .warn { margin: 0.25rem 0 0; font-size: 0.8125rem; color: var(--warn); }
      .row { display: grid; grid-template-columns: 6.5rem 1fr; gap: 0.75rem; align-items: baseline; border-top: 1px solid var(--line); padding: 0.375rem 0; }
      .label { font-size: 0.75rem; color: var(--muted); font-variant-numeric: tabular-nums; }
      .sample, .sample-ext { margin: 0; font-size: var(--size, 1.75rem); line-height: 1.3; overflow-wrap: anywhere; }
      .sample-ext { font-size: calc(var(--size, 1.75rem) * 0.7); }
      [hidden] { display: none; }
    </style>
  </head>
  <body>
    <div class="bar">
      <h1>Font library · ${families.length} families</h1>
      <label>Text <input id="text" type="text" value="${escapeHtml(manifest.sampleText)}" /></label>
      <label>Size <input id="size" type="range" min="14" max="64" value="28" /></label>
      <label>Filter <input id="filter" type="search" placeholder="family or id" /></label>
    </div>
    <main>
${sections.join('\n')}
    </main>
    <script>
      const samples = document.querySelectorAll('.sample');
      document.getElementById('text').addEventListener('input', (e) => {
        for (const el of samples) el.textContent = e.target.value;
      });
      document.getElementById('size').addEventListener('input', (e) => {
        document.documentElement.style.setProperty('--size', e.target.value / 16 + 'rem');
      });
      document.getElementById('filter').addEventListener('input', (e) => {
        const q = e.target.value.trim().toLowerCase();
        for (const card of document.querySelectorAll('.family')) card.hidden = !card.dataset.name.includes(q);
        for (const section of document.querySelectorAll('main section')) {
          section.hidden = !section.querySelector('.family:not([hidden])');
        }
      });
    </script>
  </body>
</html>
`;
}
