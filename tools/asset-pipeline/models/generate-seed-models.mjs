// Writes sql/seed_models.sql (tbl_models) from the manifest, the optimized GLBs and the source credits.
// Usage: node models/generate-seed-models.mjs
import { existsSync, statSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { readCredit, readGlbJson } from './lib/glb.mjs';
import { loadManifest, MODELS_DIR } from './lib/manifest.mjs';

const SEED_PATH = resolve(MODELS_DIR, '../../../sql/seed_models.sql');

const COLUMNS = [
  'slug',
  'name_de',
  'name_en',
  'occasion',
  'file_path',
  'preview_path',
  'file_size_bytes',
  'fit_size',
  'y_offset',
  'exposure',
  'camera_distance',
  'camera_height',
  'auto_rotate_speed',
  'credit',
  'position',
  'active',
  'created_at',
  'updated_at',
];
const NOT_UPDATED = new Set(['slug', 'created_at']);

const SQL_ESCAPES = {
  '\\': '\\\\',
  "'": "''",
  '\0': '\\0',
  '\n': '\\n',
  '\r': '\\r',
  '\x1a': '\\Z',
};
const sqlString = (value) =>
  value === null ? 'NULL' : `'${String(value).replace(/[\\'\0\n\r\x1a]/g, (c) => SQL_ESCAPES[c])}'`;
const sqlDecimal = (value) => value.toFixed(2);

const manifest = loadManifest();
const models = [...manifest.models].sort((a, b) => a.position - b.position);

const missing = models.flatMap((m) =>
  [m.outputPath, m.previewPath]
    .filter((path) => !existsSync(path))
    .map((path) => `${m.slug}: ${path}`),
);
if (missing.length) {
  throw new Error(
    `Run models:optimize and models:previews first, missing:\n  ${missing.join('\n  ')}`,
  );
}

const withoutCredit = [];
const statements = models.map((model) => {
  const credit = readCredit(readGlbJson(model.sourcePath));
  if (credit === null) withoutCredit.push(model.slug);
  const { scene } = model;
  const values = [
    sqlString(model.slug),
    sqlString(model.name_de),
    sqlString(model.name_en),
    sqlString(model.occasion),
    sqlString(model.relativeFilePath),
    sqlString(model.relativePreviewPath),
    String(statSync(model.outputPath).size),
    sqlDecimal(scene.fitSize),
    sqlDecimal(scene.yOffset),
    sqlDecimal(scene.exposure),
    sqlDecimal(scene.cameraDistance),
    sqlDecimal(scene.cameraHeight),
    sqlDecimal(scene.autoRotateSpeed),
    sqlString(credit),
    String(model.position),
    model.active ? '1' : '0',
    'UTC_TIMESTAMP()',
    'UTC_TIMESTAMP()',
  ];
  const updates = COLUMNS.filter((c) => !NOT_UPDATED.has(c)).map((c) =>
    c === 'updated_at' ? '  `updated_at` = UTC_TIMESTAMP()' : `  \`${c}\` = VALUES(\`${c}\`)`,
  );
  return [
    `-- ${model.slug} (${model.source})`,
    `INSERT INTO \`tbl_models\` (${COLUMNS.map((c) => `\`${c}\``).join(', ')}) VALUES`,
    `  (${values.join(', ')})`,
    'ON DUPLICATE KEY UPDATE',
    `${updates.join(',\n')};`,
  ].join('\n');
});

const header = `-- ============================================================
-- billet-studio - 3D model catalog seed (tbl_models)
-- GENERATED by tools/asset-pipeline (npm run models / models:seed) from
-- models/models.manifest.json, the optimized GLBs in billet-studio-frontend/public/models and the
-- credits in the source GLBs (asset.extras). Do not edit by hand: change the manifest and re-run.
-- Run after schema.sql and seed_roles.sql. Idempotent: re-running updates every column except
-- slug and created_at. Rows are never deleted here; retire a model with active = false.
-- file_path / preview_path are relative to app.models.base-url (MODELS_BASE_URL).
-- VALUES() instead of the row alias syntax because MariaDB 10.4 does not know the alias.
-- ============================================================

SET NAMES utf8mb4;
`;

writeFileSync(SEED_PATH, `${header}\n${statements.join('\n\n')}\n`, 'utf8');
console.log(
  `wrote ${SEED_PATH} (${models.length} models, ${models.filter((m) => m.active).length} active)`,
);
if (withoutCredit.length) console.warn(`no credit found for: ${withoutCredit.join(', ')}`);
